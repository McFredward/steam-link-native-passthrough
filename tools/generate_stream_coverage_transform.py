#!/usr/bin/env python3
"""Generate only owned patch instructions and numeric offsets, never native code.

Inputs are private local shader references. The generated patch is applied to
the actual reviewed native shader received by the cold pipeline callback.
"""
import argparse
import difflib
import hashlib
from pathlib import Path
import struct

import native_fragment_stream_coverage as coverage


def instructions(binary):
    words = struct.unpack('<%dI' % (len(binary)//4), binary)
    result, at = [], 5
    while at < len(words):
        n = words[at] >> 16
        if not n or at+n > len(words):
            raise ValueError('invalid instruction framing')
        result.append(tuple(words[at:at+n]));at += n
    return words[:5], result


def generate(originals):
    out = ['#pragma once', '// Generated by tools/generate_stream_coverage_transform.py.',
           '// Owned additions, interface replacements and numeric offsets only.',
           '// Native executable bodies are obtained solely from live callbacks.',
           'namespace stream_bridge_coverage_transform::detail {',
           'struct Patch {std::size_t offset,remove,first,count;};',
           'struct Program {const Patch* patches;std::size_t count;const std::uint32_t* additions;',
           '    std::size_t bytes;std::uint32_t bound;const char* sha256;};']
    names=[]
    for profile, original in zip(('Stable','Current'),originals):
        original=coverage.shader_contract.normalize(original)
        _,native=instructions(original)
        for camera in (False,True):
            binary,_=coverage.transform(original,camera_only=camera)
            header,owned=instructions(binary)
            additions,patches=[],[]
            offsets=[5]
            for item in native:offsets.append(offsets[-1]+len(item))
            for tag,a,b,c,d in difflib.SequenceMatcher(None,native,owned,autojunk=False).get_opcodes():
                if tag=='equal':continue
                # Only the owned descriptor-variable type and final RGBA
                # store may replace original instructions. All other changes
                # are insertions, including branch-local reads and Phi values.
                for item in native[a:b]:
                    op=item[0]&65535
                    if op not in (59,62):raise ValueError('native executable instruction removed')
                flat=[word for item in owned[c:d] for word in item]
                patches.append((offsets[a],offsets[b]-offsets[a],len(additions),len(flat)))
                additions.extend(flat)
            name=profile+('Camera' if camera else 'Coverage');names.append(name)
            out.append('inline constexpr std::uint32_t '+name+'Words[]={')
            for at in range(0,len(additions),10):out.append('    '+','.join(str(v)+'u' for v in additions[at:at+10])+',')
            out+=['};','inline constexpr Patch '+name+'Patches[]={']
            out+=['    {'+','.join(str(v)+'u' for v in patch)+'},' for patch in patches]
            out+=['};','inline constexpr Program '+name+'{'+name+'Patches,sizeof('+name+'Patches)/sizeof(Patch),'+name+'Words,'+
                  str(len(binary))+'u,'+str(header[3])+'u,"'+hashlib.sha256(binary).hexdigest()+'"};']
    out.append('} // namespace stream_bridge_coverage_transform::detail')
    return '\n'.join(out)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stable',required=True,type=Path)
    parser.add_argument('--current',required=True,type=Path)
    parser.add_argument('--output',required=True,type=Path)
    args=parser.parse_args()
    args.output.write_text(generate([args.stable.read_bytes(),args.current.read_bytes()]))


if __name__=='__main__':main()
